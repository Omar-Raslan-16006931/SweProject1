const { Client, check, setSection, dbc, D, L, u, ObjectId, newUser, pay, sendWebhook, png, form, isoDate } = require('./lib');
const { mkFlight, ECO, BUS } = require('./t3_flights');
const { adult } = require('./t4_fbook');

module.exports = async function round2(ctx) {
  const admin = ctx.admin; const mod = ctx.airMod; const hm = ctx.hotelMod; const g = new Client(); const db = await dbc();
  let r;

  setSection('R2 — accounts');
  const x = await newUser('Round Two');
  r = await x.patch('/users/me', { phone: '' });
  check('ACC-09', 'phone can be cleared or empty string rejected cleanly (no 500)', r.status === 200 || r.status === 400, r.status);
  r = await x.patch('/users/me', { name: '   ' });
  check('ACC-09', 'whitespace-only name rejected', r.status === 400, r.status);
  r = await x.patch('/users/me', {});
  check('ACC-09', 'empty profile update is harmless', r.status === 200, r.status);
  r = await g.post('/auth/register', { name: 'A', email: `${u('a')}@qa.test`, password: 'Passw0rd1', acceptTerms: true, extra: 1 });
  check('GEN-13', 'unknown fields rejected', r.status === 400, r.status);
  r = await g.post('/auth/login', { email: 'x@qa.test' });
  check('ACC-04', 'login without password -> 400/401, not 500', r.status === 400 || r.status === 401, r.status);
  r = await x.patch('/auth/change-password', { currentPassword: 'Passw0rd1', newPassword: 'A1' + 'x'.repeat(100) });
  check('ACC-08', 'over-long new password rejected', r.status === 400, r.status);
  const ex = await newUser('Expired token');
  const tok = ex.cookies.access_token;
  r = await admin.post(`/admin/users/${ex.id}/reset-password`, { temporaryPassword: 'Temp12345' });
  const reuse = new Client(); reuse.cookies.access_token = tok;
  r = await reuse.get('/auth/me');
  check('ACC-07a', 'access token issued before an admin reset is dead', r.status === 401, r.status);
  r = await admin.get('/admin/accounts?status=suspended');
  check('ACC-14', 'status filter works', r.status === 200 && r.data.items.every((a) => a.status === 'suspended'), r.data.items?.map((a) => a.status));
  r = await admin.get('/admin/accounts?q=%20%20');
  check('ACC-14', 'blank search returns everything (no crash)', r.status === 200 && r.data.total > 0, r.status);

  setSection('R2 — flights');
  r = await mkFlight(mod, { from: 'CAI', to: 'DXB', dep: L(50, '10:00'), arr: L(80, '10:00') });
  check('FLT-03 (dumb input)', 'a 30-day "flight" is rejected', r.status === 400, r.status);
  r = await mkFlight(mod, { from: 'CAI', to: 'RUH', dep: L(50, '10:00'), arr: L(50, '11:01') }); // 08:00Z -> 08:01Z
  check('FLT-03', 'a 1-minute flight is technically valid (arrival after departure)', r.status === 201, r.status);
  r = await mkFlight(mod, { from: 'JFK', to: 'HND', dep: L(50, '10:00'), arr: L(51, '14:00') });
  check('FLT-03', 'long-haul crossing the date line accepted (JFK 10:00 -> HND +1 day 14:00)', r.status === 201 && r.data.durationMinutes === 14 * 60, r.data?.durationMinutes);
  const big = (await mkFlight(mod, { from: 'CAI', to: 'RUH', dep: L(55, '10:00'), arr: L(55, '13:00'), cabins: [{ ...ECO(), price: 1e12 }] }));
  check('FLT-04 (dumb input)', 'absurd seat price (1,000,000,000,000) rejected', big.status === 400, big.status);
  const hugeSeats = await mkFlight(mod, { from: 'CAI', to: 'RUH', dep: L(56, '10:00'), arr: L(56, '13:00'), cabins: [{ ...ECO(), seats: 10000000 }] });
  check('FLT-04 (dumb input)', 'absurd seat count (10 million) rejected', hugeSeats.status === 400, hugeSeats.status);
  r = await mkFlight(mod, { from: 'CAI', to: 'RUH', dep: '2999-01-01T10:00', arr: '2999-01-01T13:00' });
  check('FLT-03 (dumb input)', 'departure in year 2999 rejected', r.status === 400, r.status);
  r = await mod.put(`/airlines/${ctx.airline.id}/baggage-policy`, { extraBagPrice: 1e12, maxExtraBags: 2 });
  check('FLT-08 (dumb input)', 'absurd extra-bag price rejected', r.status === 400, r.status);
  r = await mod.put(`/airlines/${ctx.airline.id}/baggage-policy`, { extraBagPrice: 50, maxExtraBags: 1000 });
  check('FLT-08 (dumb input)', 'absurd max extra bags (1000) rejected', r.status === 400, r.status);
  // moving a flight's date onto a duplicate number
  const no = 'QZ' + Math.floor(Math.random() * 900 + 100);
  const f1 = (await mkFlight(mod, { no, from: 'CAI', to: 'CDG', dep: L(60, '10:00'), arr: L(60, '14:00') })).data;
  const f2 = (await mkFlight(mod, { no, from: 'CAI', to: 'CDG', dep: L(61, '10:00'), arr: L(61, '14:00') })).data;
  r = await mod.patch(`/flights/${f2.id}`, { departureLocal: L(60, '18:00'), arrivalLocal: L(60, '22:00') });
  check('FLT-03/05', 'editing a flight onto the date of a same-number flight rejected 409', r.status === 409, r.status);
  // round trip: outbound moved after return
  const out = (await mkFlight(mod, { from: 'CAI', to: 'CDG', dep: L(62, '08:00'), arr: L(62, '12:00'), cabins: [ECO(10, 100)] })).data;
  const back = (await mkFlight(mod, { from: 'CDG', to: 'CAI', dep: L(64, '08:00'), arr: L(64, '12:00'), cabins: [ECO(10, 100)] })).data;
  const rtUser = await newUser('RT user');
  const rt = (await rtUser.post('/flight-bookings/hold', { outboundFlightId: out.id, outboundCabinClass: 'Economy', returnFlightId: back.id, returnCabinClass: 'Economy', passengers: [adult()] })).data;
  await pay(rtUser, 'flight', rt.id);
  r = await mod.patch(`/flights/${out.id}`, { departureLocal: L(65, '08:00'), arrivalLocal: L(65, '12:00') });
  check('FLT-05 (dumb input)', 'outbound cannot be moved after the return flight of a booked round trip', r.status === 400 || r.status === 409, r.status);
  // seat reduce while held
  const fh = (await mkFlight(mod, { from: 'CAI', to: 'CDG', dep: L(63, '08:00'), arr: L(63, '12:00'), cabins: [ECO(3, 100)] })).data;
  await rtUser.post('/flight-bookings/hold', { outboundFlightId: fh.id, outboundCabinClass: 'Economy', passengers: [adult(), adult()] });
  r = await mod.patch(`/flights/${fh.id}/cabins/${fh.cabins[0].id}`, { seats: 1 });
  check('FLT-05', 'seats cannot go below held seats', r.status === 400, r.status);
  r = await g.get('/flights/search?' + new URLSearchParams({ from: 'CAI', to: 'CDG', date: D(62), page: 99 }));
  check('GEN-05', 'search page past the end -> empty page', r.status === 200 && r.data.outbound.items.length === 0, r.status);
  r = await rtUser.post('/flight-bookings', { outboundFlightId: out.id, outboundCabinClass: 'Economy', passengers: [{ ...adult(), fullName: '12345' }] });
  check('FLT-19 (dumb input)', 'passenger name made only of digits rejected', r.status === 400, r.status);
  r = await rtUser.post('/flight-bookings', { outboundFlightId: out.id, outboundCabinClass: 'Economy', passengers: [{ ...adult(), fullName: '!!!' }] });
  check('FLT-19 (dumb input)', 'passenger name made only of symbols rejected', r.status === 400, r.status);
  r = await rtUser.post('/flight-bookings', { outboundFlightId: out.id, outboundCabinClass: 'Economy', passengers: [{ ...adult(), fullName: "Ana-María O'Brien" }] });
  check('FLT-19', 'real names with hyphens/apostrophes/accents accepted', r.status === 200, r.data?.message);
  r = await rtUser.post('/flight-bookings', { outboundFlightId: out.id, outboundCabinClass: 'Economy', passengers: [{ ...adult(), fullName: 'محمد علي' }] });
  check('FLT-19', 'Arabic names accepted', r.status === 200, r.data?.message);

  setSection('R2 — payments');
  const pu = await newUser('Pay edge');
  const hb = (await pu.post('/flight-bookings/hold', { outboundFlightId: out.id, outboundCabinClass: 'Economy', passengers: [adult()] })).data;
  r = await pu.post('/payments', { bookingType: 'hotel', bookingId: hb.id });
  check('PAY-01', 'wrong booking type for an id -> 404', r.status === 404, r.status);
  await pu.post(`/bookings/flight/${hb.id}/accept-policies`);
  const pp = (await pu.post('/payments', { bookingType: 'flight', bookingId: hb.id })).data;
  r = await rtUser.post(`/payments/${pp.id}/test-confirm`, {});
  check('ACC-11', "cannot confirm someone else's payment", r.status === 404 || r.status === 403, r.status);
  r = await rtUser.post(`/payments/${pp.id}/retry`);
  check('ACC-11', "cannot retry someone else's payment", r.status === 404 || r.status === 403, r.status);
  r = await sendWebhook('customer.created', { id: 'cus_1' });
  check('PAY-01', 'unrelated webhook event acknowledged', r.status === 200, r.status);
  r = await sendWebhook('payment_intent.succeeded', { id: 'pi_unknown', object: 'payment_intent' });
  check('PAY-01', 'webhook for unknown PaymentIntent ignored safely', r.status === 200, r.status);
  await pay(pu, 'flight', hb.id, { accept: false });
  r = await pu.post(`/payments/${pp.id}/retry`);
  check('PAY-01', 'retry after success refused', r.status === 409, r.status);

  setSection('R2 — hotels');
  const R = ctx.R; const H = ctx.hotel.id;
  r = await hm.patch(`/hotels/${H}/rooms/${R['104'].id}`, { maxOccupancy: 0 });
  check('HTL-05', 'occupancy 0 rejected', r.status === 400, r.status);
  r = await hm.post(`/hotels/${H}/rooms`, { number: 'X1', type: 'Double', beds: 1, maxOccupancy: 500, pricePerNight: 50 });
  check('HTL-03 (dumb input)', 'absurd occupancy (500 in one room) rejected', r.status === 400, r.status);
  r = await hm.post(`/hotels/${H}/rooms`, { number: 'X2', type: 'Double', beds: 1, maxOccupancy: 2, pricePerNight: 1e12 });
  check('HTL-03 (dumb input)', 'absurd nightly price rejected', r.status === 400, r.status);
  r = await hm.post(`/hotels/${H}/rooms`, { number: 'X3', type: 'Double', beds: 6, maxOccupancy: 2, pricePerNight: 50 });
  check('HTL-03 (dumb input)', 'more beds than allowed guests is odd but harmless (accepted or rejected, no 500)', r.status < 500, r.status);
  const hu = await newUser('Long stay');
  r = await hu.post('/hotel-bookings', { hotelId: H, checkIn: D(62), checkOut: D(62 + 400), rooms: [{ roomId: R['101'].id, adults: 1 }] });
  check('HTL-16', 'stay beyond the bookable range rejected (no 500)', r.status === 409 || r.status === 400, r.status);
  r = await g.get('/hotels/search?' + new URLSearchParams({ cityId: 'cairo', checkIn: D(10), checkOut: D(3000), guests: 1 }));
  check('HTL-11 (dumb input)', '8-year stay search answers quickly with a clear result or error', r.status === 200 || r.status === 400, r.status);
  r = await g.get(`/hotels/${H}?checkIn=${D(5)}`);
  check('HTL-02', 'details with only checkIn still works', r.status === 200, r.status);
  r = await g.get(`/hotels/${H}?checkIn=${D(5)}&checkOut=${D(2)}`);
  check('HTL-02', 'details with checkOut before checkIn -> 400', r.status === 400, r.status);

  setSection('R2 — itineraries');
  const iu = await newUser('Itn R2');
  r = await iu.post('/itineraries', { title: '    ', countries: ['EG'], startDate: D(20) });
  check('ITN-01', 'whitespace title rejected', r.status === 400, r.status);
  const it = (await iu.post('/itineraries', { title: 'Egypt only', countries: ['EG'], startDate: D(20) })).data;
  r = await iu.post(`/itineraries/${it.id}/days`, { cityId: 'tokyo' });
  check('ITN-05 (dumb input)', "day in a city outside the itinerary's countries rejected (Tokyo in an Egypt-only trip)", r.status === 400, r.status);
  await iu.post(`/itineraries/${it.id}/days`, { cityId: 'cairo' });
  r = await iu.patch(`/itineraries/${it.id}`, { countries: ['FR'] });
  check('ITN-01 (dumb input)', 'cannot drop a country that still has days in it', r.status === 400, r.status);
  r = await iu.patch(`/itineraries/${it.id}/days/reorder`, { dayId: 'nope', position: 1 });
  check('ITN-08', 'malformed day id rejected 400/404', r.status === 400 || r.status === 404, r.status);
  const day = (await iu.get(`/itineraries/${it.id}`)).data.days[0];
  r = await iu.post(`/itineraries/${it.id}/days/${day.id}/budgets`, { category: 'food', amount: 1e15, currency: 'USD' });
  check('ITN-14 (dumb input)', 'absurd budget amount rejected', r.status === 400, r.status);
  r = await iu.post(`/itineraries/${it.id}/days/${day.id}/budgets`, { category: 'food', amount: 10.999, currency: 'USD' });
  check('ITN-14', 'amounts with more than 2 decimals rejected', r.status === 400, r.status);
  r = await iu.post(`/itineraries/${it.id}/days/${day.id}/activities`, { name: 'x', cost: 1e15, currency: 'USD' });
  check('ITN-10 (dumb input)', 'absurd activity cost rejected', r.status === 400, r.status);
  r = await iu.patch(`/itineraries/${it.id}`, { startDate: '1900-01-01' });
  check('ITN-01 (dumb input)', 'start date in 1900 rejected', r.status === 400, r.status);
  r = await iu.patch(`/itineraries/${it.id}`, { startDate: '2999-01-01' });
  check('ITN-01 (dumb input)', 'start date in 2999 rejected', r.status === 400, r.status);

  setSection('R2 — blog & reports');
  const bu = await newUser('Blog R2'); const bv = await newUser('Blog R2 reader');
  r = await bu.post('/posts', { title: '   ', body: 'b' });
  check('BLG-01', 'whitespace title rejected', r.status === 400, r.status);
  const pst = (await bu.post('/posts', { title: 'Hello', body: 'b', status: 'Published' })).data;
  const cm = (await bv.post(`/posts/${pst.id}/comments`, { body: 'nice' })).data;
  await admin.patch(`/admin/content/post/${pst.id}/visibility`, { hidden: true });
  r = await bu.post('/reports', { targetType: 'comment', targetId: cm.id, reason: 'x' });
  check('GEN-09', 'comment on a hidden post cannot be reported (not publicly visible)', r.status === 404, r.status);
  r = await bv.patch(`/comments/${cm.id}`, { body: 'edited' });
  check('BLG-07', 'comment author can still manage own comment', r.status === 200, r.status);
  r = await g.get(`/posts/${pst.id}/comments`);
  check('GEN-10', "comments of a hidden post not readable by guests", r.status === 404, r.status);
  r = await bu.post('/posts', { title: 'T', body: 'B', tags: ['  ', 'ok'] });
  check('BLG-08', 'blank tags dropped', r.status === 201 && r.data.tags.join() === 'ok', r.data?.tags);
  r = await g.get('/posts?tag=' + 'x'.repeat(31));
  check('BLG-02', 'over-long tag filter rejected', r.status === 400, r.status);

  setSection('R2 — admin');
  r = await admin.get('/admin/airlines');
  check('ACC-13', 'admin provider list paginated', r.status === 200 && r.data.pageSize === 10, r.status);
  r = await admin.get('/admin/audit-logs?from=2026-13-01');
  check('GEN-07', 'invalid audit date rejected', r.status === 400, r.status);
  r = await admin.get('/admin/bookings?from=2026-02-30');
  check('ACC-17', 'impossible date filter rejected', r.status === 400, r.status);
  r = await admin.patch(`/admin/reports/${new ObjectId()}`, { action: 'dismiss' });
  check('GEN-10', 'unknown report -> 404', r.status === 404, r.status);
  r = await admin.del(`/users/me`);
  check('ACC-12', 'admin cannot self-deactivate', r.status === 403, r.status);
};
