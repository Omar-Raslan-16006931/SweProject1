  r = await admin.get('/admin/audit-logs?action=account.suspended');
  check('GEN-07', 'suspensions audited (actor + target)', r.data.items.length >= 1 && r.data.items[0].admin?.email === CFG.adminEmail && r.data.items[0].targetId, r.data.items?.[0]);
  r = await admin.get('/admin/audit-logs?action=content.deleted');
  check('GEN-07', 'deletions audited', r.data.items.length >= 2, r.data.items?.length);
  r = await admin.get('/admin/audit-logs?action=content.hidden');
  check('GEN-07', 'hides audited', r.data.items.length >= 2, r.data.items?.length);
  r = await b.get('/admin/audit-logs');
  check('GEN-07', 'non-admin cannot read audit log', r.status === 403, r.status);
  const audits = await db.collection('audit_logs').countDocuments({});
  r = await admin.del(`/admin/content/post/${p1.id}`);
  check('GEN-07', 'each moderation action writes exactly one audit row', (await db.collection('audit_logs').countDocuments({})) === audits + 1, null);

  setSection('GEN-01 — notifications');
  const nu = ctx.traveler;
  r = await nu.get('/notifications');
  check('GEN-01', 'notification list newest first with unread count', r.status === 200 && r.data.items.length > 0 && typeof r.data.unread === 'number', r.data?.unread);
  const first = r.data.items[0];
  r = await nu.get('/notifications/unread-count');
  const unread0 = r.data.unread;
  check('GEN-01', 'unread count endpoint', r.status === 200 && unread0 > 0, r.data);
  r = await nu.get('/notifications?unreadOnly=true');
  check('GEN-01', 'filter unread only (?unreadOnly=true) works', r.status === 200 && r.data.items.every((x) => !x.read), { s: r.status, m: r.data?.message, e: r.data?.errors });
  r = await nu.patch(`/notifications/${first.id}/read`);
  check('GEN-01', 'mark one as read', r.status === 200 && r.data.read === true, r.status);
  r = await nu.get('/notifications/unread-count');
  check('GEN-01', 'unread count decremented', r.data.unread === unread0 - 1, [unread0, r.data.unread]);
  r = await b.patch(`/notifications/${first.id}/read`);
  check('ACC-11', "cannot mark someone else's notification", r.status === 404, r.status);
  r = await nu.patch('/notifications/read-all');
  r = await nu.get('/notifications/unread-count');
  check('GEN-01', 'mark all read', r.data.unread === 0, r.data);
  r = await g.get('/notifications');
  check('GEN-01', 'guest has no notifications endpoint', r.status === 401, r.status);
  r = await ctx.hotelMod.get('/notifications');
  check('GEN-01', 'moderators also receive notifications', r.status === 200, r.status);

  setSection('ACC-12 — self-deactivation');
  const dz = await newUser('Leaving User');
  const dzPost = (await dz.post('/posts', { title: 'Bye post', body: 'b', status: 'Published' })).data;
  const dzComment = (await dz.post(`/posts/${p3.id}/comments`, { body: 'comment before leaving' })).data;
  const dzIt = (await dz.post('/itineraries', { title: 'Bye trip', countries: ['EG'], startDate: D(30) })).data;
  await dz.post(`/itineraries/${dzIt.id}/days`, { cityId: 'cairo' });
  await dz.patch(`/itineraries/${dzIt.id}`, { visibility: 'Public' });
  // upcoming confirmed hotel booking blocks deactivation
  const R = ctx.R;
  const hb = (await dz.post('/hotel-bookings', { hotelId: ctx.hotel.id, checkIn: D(70), checkOut: D(71), rooms: [{ roomId: R['101'].id, adults: 1 }] })).data;
  const pr = await pay(dz, 'hotel', hb?.id);
  r = await dz.del('/users/me');
  check('ACC-12', 'deactivation blocked while user has upcoming Confirmed bookings', r.status === 409, { s: r.status, pay: pr.error });
  await dz.post(`/hotel-bookings/${hb?.id}/cancel`);
  r = await ctx.airMod.del('/users/me');
  check('ACC-12', 'moderators cannot self-deactivate via this endpoint', r.status === 403, r.status);
  r = await dz.del('/users/me');
  check('ACC-12', 'deactivation succeeds without upcoming bookings', r.status === 200, r.data);
  r = await dz.get('/auth/me');
  check('ACC-12', 'session ended', r.status === 401, r.status);
  r = await new Client().login(dz.email, 'Passw0rd1');
  check('ACC-12', 'deactivated user cannot log in', r.status !== 200, r.status);
  r = await g.get(`/posts/${dzPost.id}`);
  check('ACC-12', "deactivated user's posts hidden", r.status === 404, r.status);
  r = await g.get('/itineraries/public/search?keyword=Bye');
  check('ACC-12', "deactivated user's public itineraries hidden", !r.data.items.some((x) => x.id === dzIt.id), null);
  r = await g.get(`/posts/${p3.id}`);
  const dc = r.data.comments.items.find((x) => x.id === dzComment.id);
  check('ACC-12', 'their comments still shown as "Deleted user"', dc && dc.author.name === 'Deleted user', dc);
  r = await g.get(`/authors/${dz.id}`);
  check('ACC-12', 'author page gone', r.status === 404, r.status);
  r = await admin.patch(`/admin/accounts/${dz.id}/reactivate`);
  check('ACC-12', 'admin "reactivate" does not apply to self-deactivated accounts (only suspended)', r.status === 409, r.status);

  setSection('ACC-16 — suspended user content stays visible');
  r = await admin.patch(`/admin/accounts/${b.id}/suspend`);
  r = await g.get(`/posts/${p3.id}`);
  check('ACC-16', "suspended user's content stays visible", r.status === 200, r.status);
  await admin.patch(`/admin/accounts/${b.id}/reactivate`);
